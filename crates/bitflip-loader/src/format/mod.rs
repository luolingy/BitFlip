//! 格式层：每种对象格式一个子模块。
//!
//! # 为什么要有这一层
//!
//! `bitflip-loader` 里有两类东西，它们的变化原因完全不同：
//!
//! * **通用层**（`lib.rs` / `object` / `reader` / `sniff` / `ehframe`）—— 对象模型、
//!   带边界检查的读取器、识别与展开表。它关心的是"所有格式共有的形状"，
//!   每加一种格式都**不该**改它；
//! * **格式层**（本模块）—— PE / COFF / ELF 各自的头、表、编码细节。
//!   格式规范改了、或者新增一种格式，变化都落在这一层里。
//!
//! 在此之前这些文件平摊在 `src/` 下（`pe.rs` / `coff.rs` / `elf.rs` 与通用文件
//! 混在一起），"哪个是通用的、哪个是某个格式的"只能靠文件名猜 —— 而 `pe.rs`
//! 当时有 2770 行。目录本身就是一层文档：**在 `format/` 外面的，与格式无关。**
//!
//! # 边界是硬的，不是命名习惯
//!
//! * 通用层不出现格式类型名。栈帧推导（`bitflip-analyze::frames`）曾直接 `use`
//!   `PeUnwindInfo`，于是"分析层知道 PE 的 opcode 怎么编码"；现在它只读
//!   `object::UnwindEntry` 上的格式无关访问器，加一种格式的展开信息时分析层
//!   不用改。
//! * 跨格式的派发只在一个地方：[`crate::parse_object`]。`match kind { Pe => ... }`
//!   曾在三处各写一遍，漏改一处的后果是静默的（那个格式会被报成"不是可分析对象"）。
//! * 格式之间**互不引用**（PE 不 `use` ELF，反之亦然）。要用对方的东西，说明
//!   那东西其实属于通用层，该往 [`crate::object`] 搬。
//!
//! # 现状
//!
//! | 子模块 | 内容 | 状态 |
//! |--------|------|------|
//! | [`pe`] | PE32/PE32+（exe/dll/sys） | 已按关注点拆成 `mod` / `import` / `reloc` / `unwind` / `inspect` |
//! | [`coff`] | COFF 目标文件（`.obj`） | 单文件。节名解析（`/N` 长名表）与解析主体同处一文件，尚未拆开 |
//! | [`elf`] | ELF32/64（exe/`.so`/`.o`） | 单文件（约 1950 行）。内部拆分未做 —— 见下 |
//! | [`zip`] | ZIP 容器（APK / JAR / XAPK 外壳） | 单文件。**只做容器层**：成员枚举与按需取出 |
//! | [`dex`] | DEX（Dalvik Executable） | 单文件。**只做结构模型**：类/字段/方法清单，不解码字节码、不建 CFG |
//! | [`axml`] | AXML（Android 二进制 XML） | 单文件。**只解清单**：`AndroidManifest.xml` 的字段摘要；不读 `resources.arsc`，`@` 引用原样保留 |
//! | [`macho`] | Mach-O（thin）+ fat 容器 | **M12 第一片**：头/段/节/入口/`LC_UUID`/dylib；符号表、dyld 绑定、objc/swift、代码签名**都没有**。fat 切片能枚举（[`macho::fat`]）但没接进会话 |
//!
//! ELF 的内部拆分**故意没和 PE 一起做**：PE 那一次是纯粹的搬移（逐字节校验过），
//! 一次只搬一个文件，出问题时能立刻定位。ELF 的拆分是同一类工作，单独一轮做，
//! 免得两处一起动、出了问题分不清是哪一处。
//!
//! Mach-O 也拆成了两个文件（`mod` = 薄 Mach-O，`fat` = universal 容器），
//! 理由同 PE 的拆分：读的时候解决的是两个不同问题 —— "这一层对象长什么样"与
//! "一个文件里有几层、该选哪层"。

pub mod axml;
pub mod coff;
pub mod dex;
pub mod elf;
pub mod macho;
pub mod pe;
pub mod zip;
